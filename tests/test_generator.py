def p2_answers():
    """Scenario P2: like P1, but milestones 20 / 40 / 40 and the first one an advance."""
    answers = p1_answers()  # start from P1
    answers["payment_type"] = "milestones"  # milestone payments
    answers["milestones"] = [  # the three rows of P2
        {"name": "Deposit", "trigger": "Contract signed", "percent": Decimal("20"), "invoice_due_days": 10, "advance": True},
        {"name": "Shell construction", "trigger": "Roof is closed", "percent": Decimal("40"), "invoice_due_days": 30, "advance": False},
        {"name": "Handover", "trigger": "Works delivered", "percent": Decimal("40"), "invoice_due_days": 30, "advance": False},
    ]  # end of the rows
    return answers  # P2


def generate(answers, knowledge):
    """Run the engine and the generator for these answers and return the Word file as bytes."""
    result = evaluate(answers, knowledge)  # the engine's result
    return generate_contract(result, answers, knowledge)  # the Word file


def contract_text(word_bytes):
    """Read a generated Word file and return all its text (body and footer) as one string."""
    document = Document(BytesIO(word_bytes))  # open the bytes like a file
    body = "\n".join(paragraph.text for paragraph in document.paragraphs)  # every paragraph; line breaks show as "\n"
    footer = document.sections[0].footer.paragraphs[0].text  # the footer text
    return body + "\n" + footer  # everything in one string


