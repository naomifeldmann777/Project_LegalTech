def test_refuses_when_the_result_has_errors(knowledge):
    """A result with errors (here price 0, R_PRICE) is refused, and the message names the rule."""
    answers = p1_answers()  # start from P1
    answers["contract_price"] = Decimal("0")  # R_PRICE
    result = evaluate(answers, knowledge)  # result with an error
    with pytest.raises(GenerationError, match="R_PRICE"):  # refused, message names the rule
        generate_contract(result, answers, knowledge)  # try to generate


def test_refuses_when_a_clause_gap_is_still_open(knowledge):
    """A clause text that still contains one of its own placeholders is refused."""
    result = copy.deepcopy(evaluate(p1_answers(), knowledge))  # a correct result, copied
    result["selected_clauses"][0]["text"] = "The fixed price for the Works is CHF {contract_price}."  # gap left open
    with pytest.raises(GenerationError, match="PRICE_FIXED"):  # refused, message names the clause
        generate_contract(result, p1_answers(), knowledge)  # try to generate


def test_refuses_when_a_template_gap_has_no_value(knowledge):
    """A skeleton field without an answer (and without an empty text) is refused."""
    result = evaluate(p1_answers(), knowledge)  # a correct result
    answers = p1_answers()  # the same answers ...
    answers["client_name"] = ""  # ... but the client name is missing now
    with pytest.raises(GenerationError, match="client_name"):  # refused, message names the gap
        generate_contract(result, answers, knowledge)  # try to generate


def test_refuses_an_unknown_template_gap(knowledge, tmp_path):
    """A template with a gap that is neither a slot nor a field is refused."""
    template = Document()  # a tiny test template
    template.add_paragraph("Hello {{ unknown_gap }}")  # a gap the generator does not know
    template_path = tmp_path / "test_template.docx"  # in a temporary folder
    template.save(template_path)  # save it
    result = evaluate(p1_answers(), knowledge)  # a correct result
    with pytest.raises(GenerationError, match="unknown_gap"):  # refused, message names the gap
        generate_contract(result, p1_answers(), knowledge, template_path=template_path)  # try to generate


