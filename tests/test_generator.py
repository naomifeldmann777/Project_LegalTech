def test_generator_returns_a_word_file(knowledge):
    """The result is the bytes of a .docx file (a .docx is a ZIP file, which starts with "PK")."""
    word_bytes = generate(p1_answers(), knowledge)  # generate P1
    assert isinstance(word_bytes, bytes) and word_bytes[:2] == b"PK"  # bytes of a ZIP / .docx file


