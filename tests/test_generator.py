def test_special_characters_are_kept(knowledge):
    """&, < and umlauts in answers appear unchanged and do not break the Word file."""
    answers = p1_answers()  # start from P1
    answers["client_name"] = "Müller & Söhne <Bau>"  # characters that are special in Word's XML
    text = contract_text(generate(answers, knowledge))  # generate and read back
    assert "Client: Müller & Söhne <Bau>" in text  # unchanged


def test_braces_typed_by_the_user_do_not_block_the_contract(knowledge):
    """Braces inside an answer (e.g. "{see annex}") are not mistaken for an open gap."""
    answers = p1_answers()  # start from P1
    answers["work_description"] = "New tiles {see annex 1}"  # braces typed by the user
    text = contract_text(generate(answers, knowledge))  # generated without GenerationError
    assert "New tiles {see annex 1}" in text  # copied as typed


def test_addresses_keep_their_line_breaks(knowledge):
    """Multi-line answers keep their line breaks in the contract."""
    text = contract_text(generate(p1_answers(), knowledge))  # generate and read back
    assert "Address: Seestrasse 1\n8000 Zürich" in text  # street and town on two lines
