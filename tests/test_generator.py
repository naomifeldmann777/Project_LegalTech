"""test_generator.py - automatic tests for generator.py.

What this file is for:
    It generates real Word contracts for scenarios P1 and P2 (AI_PROMPT step 16) and
    reads them back to check that:
      - the expected texts and amounts appear, and no gap ({ ... }) is left
      - the right paragraph versions are used with and without technical annexes
      - legal sources, reasons and warnings are NOT in the contract (handoff App. C)
      - the generator refuses to work when there are errors or open gaps
      - special characters (&, <, umlauts) and line breaks come out correctly

How it fits into the project:
    AI_PROMPT step 16. Run from the project root:
        python -m pytest tests/test_generator.py -v

Which documents it implements:
    AI_PROMPT steps 15 and 16, contract skeleton, law packet Tasks 13 and 14,
    law colleague's answers 2 and 3, decisions D30, D33, D35.
"""

